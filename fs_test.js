const fs = require('node:fs/promises');

async function handleFiles() {
    try {
        // A. WRITING A FILE
        // Arguments: (filePath, fileContent)
        await fs.writeFile('./log.txt', 'This is a log message generated by Node.js!\n');
        console.log('File successfully created and written to disk.');

        // B. READING A FILE
        // Arguments: (filePath, encoding) - always specify 'utf8' to read text, otherwise you got a raw Buffer project.
        const fileContents = await fs.readFile('.log.txt', 'utf8');
        console.log('File Contents Read:', fileContents);

    } catch (error) {
        console.error('Something went wrong handling the file.', error);
    }
}

handleFiles();